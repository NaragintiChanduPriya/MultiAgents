from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field, field_validator


class DischargePackageSourceData(BaseModel):
    """Container for verified database records retrieved from MongoDB."""

    model_config = ConfigDict(from_attributes=True)

    package: Optional[Dict[str, Any]] = Field(None, description="Direct columns from discharge_packages.")
    admission: Optional[Dict[str, Any]] = Field(None, description="Associated admission record details.")
    patient: Optional[Dict[str, Any]] = Field(None, description="Associated patient demographics and history.")
    medications: List[Dict[str, Any]] = Field(default_factory=list, description="Associated medications.")
    procedures: List[Dict[str, Any]] = Field(default_factory=list, description="Associated procedures.")
    lab_results: List[Dict[str, Any]] = Field(default_factory=list, description="Associated lab results.")
    clinical_notes: List[Dict[str, Any]] = Field(default_factory=list, description="Associated clinical notes.")
    vitals: List[Dict[str, Any]] = Field(default_factory=list, description="Associated vitals recordings.")


class DischargeSummaryRequest(BaseModel):
    """Request model for retrieving and generating a discharge summary report."""

    package_id: str = Field(
        ...,
        min_length=1,
        max_length=50,
        description="Unique discharge package identifier, e.g. 'DP0001'.",
        examples=["DP0001"],
    )
    session_id: Optional[str] = Field(
        None,
        description="Optional session identifier for tracking.",
    )

    @field_validator("package_id")
    @classmethod
    def validate_identifier(cls, v: str) -> str:
        clean = v.strip()
        if not clean:
            raise ValueError("package_id cannot be blank or whitespace.")
        return clean


class DischargeSummaryResponse(BaseModel):
    """Response model returning the compiled discharge summary report and verified source data."""

    package_id: str = Field(..., description="Requested discharge package identifier.")
    status: str = Field(
        "success",
        description="Operation status: 'success', 'not_found', 'forbidden', or 'error'.",
    )
    report: str = Field(
        "",
        description="Structured, clinical discharge summary report generated by the Discharge Summary Report Agent.",
    )
    source_data: Optional[DischargePackageSourceData] = Field(
        None,
        description="Verified source data from MongoDB associated with this discharge package.",
    )
    missing_information: List[str] = Field(
        default_factory=list,
        description="Explicit list of unrecorded, missing, or pending items identified in the records.",
    )
    patient_id: Optional[str] = Field(
        None,
        description="Associated patient identifier.",
    )
    error: Optional[str] = Field(
        None,
        description="Error message if the request was unsuccessful.",
    )

