from typing import Optional
from pydantic import BaseModel, ConfigDict, Field, field_validator


class MedicationRecordItem(BaseModel):
    """Pydantic model representing a verified record from the MongoDB medications collection."""

    model_config = ConfigDict(from_attributes=True)

    medication_record_id: str = Field(..., description="Unique medication record identifier (e.g. 'MED000001').")
    admission_id: str = Field(..., description="Associated hospital admission identifier (e.g. 'ADM0001').")
    patient_id: str = Field(..., description="Associated patient identifier (e.g. 'PAT0019').")
    medication_name: str = Field(..., description="Name of the prescribed or documented medication.")
    drug_class: Optional[str] = Field(None, description="Therapeutic drug classification.")
    strength: str = Field(..., description="Recorded strength text (e.g. '100 mcg', '20 mg').")
    strength_value: Optional[float] = Field(None, description="Numeric magnitude of the dose strength.")
    strength_unit: str = Field(..., description="Unit of measurement for the dose strength (e.g. 'mcg', 'mg').")
    route: str = Field(..., description="Route of administration (e.g. 'Oral', 'Inhalation', 'Injection').")
    medication_type: str = Field(..., description="Classification category (e.g. 'Home', 'Inpatient', 'Discharge').")
    dose_instructions: str = Field(..., description="Directions for medication use.")
    medication_status: str = Field(..., description="Current status of the medication order.")


class MedicationDetailRequest(BaseModel):
    """Request model for retrieving and explaining a medication record."""

    medication_record_id: str = Field(
        ...,
        min_length=1,
        max_length=50,
        description="The unique medication record identifier, e.g. 'MED000001'.",
        examples=["MED000001"],
    )
    session_id: Optional[str] = Field(
        None,
        description="Optional session identifier for multi-turn tracking.",
    )

    @field_validator("medication_record_id")
    @classmethod
    def validate_identifier(cls, v: str) -> str:
        clean = v.strip()
        if not clean:
            raise ValueError("medication_record_id cannot be blank or whitespace.")
        return clean


class MedicationDetailResponse(BaseModel):
    """Response model returning verified medication database records and human-readable explanation."""

    medication_record_id: str = Field(..., description="Requested medication record identifier.")
    status: str = Field(
        "success",
        description="Operation status: 'success', 'not_found', 'forbidden', or 'error'.",
    )
    record: Optional[MedicationRecordItem] = Field(
        None,
        description="Verified database record from the MongoDB medications collection.",
    )
    explanation: str = Field(
        "",
        description="Patient-friendly educational explanation generated by the Medication Agent.",
    )
    patient_id: Optional[str] = Field(
        None,
        description="Associated patient identifier.",
    )
    error: Optional[str] = Field(
        None,
        description="Error detail message if the operation was not successful.",
    )



class PrescriptionCounsellingRequest(BaseModel):
    """Request to write the take-home sheet for one prescription."""

    prescription_id: str = Field(
        ...,
        min_length=1,
        max_length=64,
        description="The prescription identifier (e.g. 'RX-20261101-0001').",
    )
    session_id: Optional[str] = Field(
        default=None,
        description="Optional conversation session identifier.",
    )


class PrescriptionCounsellingResponse(BaseModel):
    """The plain-language counselling sheet the patient takes home."""

    prescription_id: str = Field(..., description="The prescription that was counselled on.")
    status: str = Field(..., description="'success', 'not_found', 'forbidden' or 'error'.")
    counselling: str = Field(
        default="",
        description="Patient-facing guidance written from the verified prescription.",
    )
    error: Optional[str] = Field(default=None, description="Failure detail, when unsuccessful.")
